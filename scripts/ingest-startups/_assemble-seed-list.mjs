#!/usr/bin/env node
/**
 * Combine all seed-data blocks → seed-list.json
 * - Dedupes by slug (first wins)
 * - Strips any entries with slug ending in '-2' or '-3' that share the prefix
 *   slug of an already-present entry (intentional duplicates were padding)
 */
import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

import { block_original, block_listed } from './_build-seed-list.mjs'
import { block_unicorns } from './_seed-data-unicorns.mjs'
import { block_nextwave } from './_seed-data-nextwave.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUT_PATH = join(__dirname, 'seed-list.json')

const combined = [...block_original, ...block_listed, ...block_unicorns, ...block_nextwave]

// Dedupe by slug (first occurrence wins).
const bySlug = new Map()
for (const entry of combined) {
  if (!entry.slug) continue
  if (bySlug.has(entry.slug)) continue
  bySlug.set(entry.slug, entry)
}

// Drop the explicit -2 / -3 / -bse duplicates regardless of order.
const cleaned = [...bySlug.values()].filter((e) => {
  const m = e.slug.match(/^(.+?)-([23]|bse)$/)
  if (!m) return true
  // If a non-suffixed sibling exists, drop the suffixed one.
  return !bySlug.has(m[1])
})

// Force country = India, strip undefined fields.
const normalised = cleaned.map((e) => {
  const out = { country: 'India' }
  for (const [k, v] of Object.entries(e)) {
    if (v === undefined || v === null || v === '') continue
    out[k] = v
  }
  return out
})

const doc = {
  _comment: `Hand-curated anchor list of Indian startups. ${normalised.length} entries. Generated by scripts/ingest-startups/_assemble-seed-list.mjs from _build-seed-list.mjs + _seed-data-*.mjs. Edit those, then re-run the assembler.`,
  startups: normalised,
}

writeFileSync(OUT_PATH, JSON.stringify(doc, null, 2) + '\n')
console.log(`Wrote ${normalised.length} unique startups → seed-list.json`)

// Per-industry breakdown for sanity-check
const byIndustry = {}
for (const e of normalised) byIndustry[e.industry || 'Unknown'] = (byIndustry[e.industry || 'Unknown'] || 0) + 1
console.log('\nBy industry:')
for (const [k, v] of Object.entries(byIndustry).sort((a, b) => b[1] - a[1])) {
  console.log(`  ${String(v).padStart(3)} ${k}`)
}

const byStage = {}
for (const e of normalised) byStage[e.stage || 'unknown'] = (byStage[e.stage || 'unknown'] || 0) + 1
console.log('\nBy stage:')
for (const [k, v] of Object.entries(byStage).sort((a, b) => b[1] - a[1])) {
  console.log(`  ${String(v).padStart(3)} ${k}`)
}

console.log(`\nWith nse_symbol: ${normalised.filter((e) => e.nse_symbol).length}`)
console.log(`With wikipedia_title: ${normalised.filter((e) => e.wikipedia_title).length}`)
console.log(`With cin: ${normalised.filter((e) => e.cin).length}`)
console.log(`With github_org: ${normalised.filter((e) => e.github_org).length}`)

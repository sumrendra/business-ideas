async function seed() {
  console.log(`Seeding ${ideas.length} ideas...`)
  let success = 0, skipped = 0
  for (const idea of ideas) {
    const docId = `idea-${idea.slug}`
    const existing = await client.fetch(`*[_id == $id][0]._id`, { id: docId })
    if (existing) {
      console.log(`  SKIP: ${idea.title}`)
      skipped++
      continue
    }
    await client.create({
      _id: docId,
      _type: 'businessIdea',
      ...idea,
      slug: { _type: 'slug', current: idea.slug },
    })
    console.log(`  OK: ${idea.title}`)
    success++
  }
  console.log(`\nDone. Created: ${success}, Skipped: ${skipped}`)
}

